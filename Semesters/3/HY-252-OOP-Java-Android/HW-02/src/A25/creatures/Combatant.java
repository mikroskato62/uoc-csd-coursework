// * Ένας Combatant – interface – πρέπει να υλοποιεί τις παρακάτω μεθόδους:
// • void attack(Object adversary) * Επιτίθεται σε έναν αντίπαλο, ο οποίος θα πρέπει να είναι επίσης Combatant.
//   Μια οντότητα δεν μπορεί να επιτεθεί στον εαυτό της. Ο Combatant που επιτίθεται πρέπει να έχει κατάσταση > 0.
//   Στο τέλος της επίθεσης τυπώνεται ότι η τρέχουσα οντότητα (με το όνομά της) επιτέθηκε στον adversary
//   (με το όνομά του), καθώς και η νέα κατάσταση του adversary. Μετά την επίθεση, η κατάσταση του adversary
//   θα πρέπει να είναι μικρότερη από την προηγούμενή του.
// • boolean isDefeated() * Επιστρέφει αν η οντότητα έχει ηττηθεί (δηλαδή η κατάστασή της είναι 0).
// • int getCondition(), void setCondition(int condition) * Επιστρέφει και θέτει την κατάσταση της οντότητας,
//   η οποία ορίζεται στο διάστημα [0,10].
// • String getCallSign() * Επιστρέφει το όνομα που χρησιμοποιεί η οντότητα στη μάχη.
// ---------------------------------------------------------------------------------------------------- //

package A25.creatures;

public interface Combatant
{
    public void attack (Object adversary);

    public boolean isDefeated();

    public int getCondition();
    public void setCondition (int condition);

    public String getCallSign();
}

